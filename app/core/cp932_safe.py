def _encode_ok(s: str) -> bool:
    try:
        s.encode(CP932)
        return True
    except UnicodeEncodeError:
        return False


# Drop entries whose replacement cannot encode; also drop identity no-ops that fail
_CHAR_TO_SAFE = {
    k: v
    for k, v in _CHAR_TO_SAFE.items()
    if v and _encode_ok(v) and not _encode_ok(k)
}


def _repair_old_aggressive(t: str) -> str:
    """Undo old maps: 什麼→何, sentence-final 吧→罷, etc."""
    parks: dict[str, str] = {}

    for word in _PROTECT_WORDS:
        if word not in t:
            continue
        key = f"\0P{len(parks)}\0"
        parks[key] = word
        t = t.replace(word, key)

    # 旧版把「什麼」整词收成「何」后，常见尾巴还在
    t = re.sub(r"何([呀吶呢嘛哦了！!？?～~…\.。])", r"什麼\1", t)
    t = re.sub(r"([是有看做幹干給给問问])何", r"\1什麼", t)

    # 旧版句尾语气「吧」→「罷」：保护词之外改成「唄」
    t = re.sub(r"罷([！!？?」』…\s]|$)", r"唄\1", t)

    for key, val in parks.items():
        t = t.replace(key, val)
    return t


def to_cp932_safe(text: str) -> str:
    if not text:
        return text
    t = text
    # 简体常见词先收成可进 CP932 的繁体，避免被旧伤修复误伤
    for a, b in (
        ("为什么", "為什麼"),
        ("什么", "什麼"),
        ("为何", "為何"),
        ("怎么", "怎麼"),
        ("那么", "那麼"),
        ("这样", "這樣"),
        ("那样", "那樣"),
        ("这里", "這裡"),
        ("那里", "那裡"),
        ("诅咒", "呪詛"),
        ("陷阱", "陥穽"),
        ("蘑菇", "茸菇"),
        ("牛磺酸", "タウリン"),
        ("奶油", "クリーム"),
        ("铀", "ウラン"),
        ("手榴弹", "手榴弾"),
        ("炸弹", "爆弾"),
        ("传送", "伝送"),
        ("继续", "継続"),
        ("行动", "行動"),
        ("爱好", "愛好"),
        ("满腹", "満腹"),
        ("其实", "其実"),
        ("迷宫", "迷宮"),
    ):
        t = t.replace(a, b)
    t = _repair_old_aggressive(t)
    # 连声「啊啊啊」→「あああ」，单字语气「啊」稍后再换成「呀」
    t = re.sub(r"啊{2,}", lambda m: "あ" * len(m.group(0)), t)
    for a, b in _SUBS:
        if a in t and _encode_ok(b):
            t = t.replace(a, b)
    out: list[str] = []
    for i, ch in enumerate(t):
        if _encode_ok(ch):
            out.append(ch)
            continue
        if ch in ("嗎", "吗"):
            nxt = t[i + 1] if i + 1 < len(t) else ""
            out.append("" if nxt in "？?" else "？")
            continue
        if ch in _CHAR_TO_SAFE:
            out.append(_CHAR_TO_SAFE[ch])
            continue
        if ch == "…":
            out.append("...")
            continue
        if ch in "─—–―－":
            out.append("─" if _encode_ok("─") else "-")
            continue
        out.append("・")
    result = "".join(out)
    result = re.sub(r"呀{2,}", lambda m: "あ" * len(m.group(0)), result)
    if not _encode_ok(result):
        result = "".join(ch if _encode_ok(ch) else "・" for ch in result)
    return result


def explain_dots() -> str:
    return (
        "缺字「点」常见有两种原因：\n"
        "1) 游戏字体不含该汉字 → 换/拷贝微软雅黑等中文字体进游戏目录；\n"
        "2) 古早引擎只用 CP932 编码、根本存不下该字 → 勾选 CP932 可显示字形，"
        "或用日语 Locale + 代理。\n"
        "现代 UTF 游戏请关闭 CP932，并安装中文字体，保留完整汉字。"
    )


def validate_cp932(text: str) -> bool:
    return _encode_ok(text)
